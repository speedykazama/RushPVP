-----------------------------------------------------------------------------------------------------------------------------------------
-- VRP
-----------------------------------------------------------------------------------------------------------------------------------------
local Tunnel = module("vrp","lib/Tunnel")
local Proxy = module("vrp","lib/Proxy")
vRP = Proxy.getInterface("vRP")
-----------------------------------------------------------------------------------------------------------------------------------------
-- CONNECTION
-----------------------------------------------------------------------------------------------------------------------------------------
Creative = {}
Tunnel.bindInterface("cards", Creative)
-----------------------------------------------------------------------------------------------------------------------------------------
-- CARDS:OPEN
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNetEvent("cards:Open")
AddEventHandler("cards:Open", function()
	SetNuiFocus(true, true)
	vRP.CreateObjects("amb@medic@standing@timeofdeath@base","base","prop_notepad_01",49,60309)
	TriggerEvent("Notify", "amarelo", "Raspe o espaço inteiro para resgatar o prêmio.", 10000)
	SendNUIMessage({ action = "open", minPrice = 1, maxPrice = 100, tryAgainPercentage = 0.7 })
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- EXIT
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("exit", function()
	SetNuiFocus(false, false)
	vRP.Destroy("one")
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- GIVEMONEY
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("giveMoney", function(data)
	local Value = tonumber(data.price)
	TriggerServerEvent("cards:Payment", Value)
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- VRP
-----------------------------------------------------------------------------------------------------------------------------------------
local Tunnel = module("vrp","lib/Tunnel")
local Proxy = module("vrp","lib/Proxy")
vRP = Proxy.getInterface("vRP")
-----------------------------------------------------------------------------------------------------------------------------------------
-- CONNECTION
-----------------------------------------------------------------------------------------------------------------------------------------
Creative = {}
Tunnel.bindInterface("painel",Creative)
vSERVER = Tunnel.getInterface("painel")
-----------------------------------------------------------------------------------------------------------------------------------------
-- VARIÁVEIS
-----------------------------------------------------------------------------------------------------------------------------------------
local memberData = {}
local OrgName = ""
local max = 0
local MembersOnline = 0
-----------------------------------------------------------------------------------------------------------------------------------------
-- OPEN
-----------------------------------------------------------------------------------------------------------------------------------------
function Creative.Open(Data)
	memberData = Data.members
	OrgName = Data.groupName
	max = Data.max
	MembersOnline = Data.totalOnline

	SetNuiFocus(true,true)
	TransitionToBlurred(1000)
	SendNUIMessage({ action = "showUi" })
	vRP.CreateObjects("amb@code_human_in_bus_passenger_idles@female@tablet@base","base","prop_cs_tablet",50,28422)
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- OPEN
-----------------------------------------------------------------------------------------------------------------------------------------
local function MemberList()
	local Data = vSERVER.MemberList(OrgName)
	if not Data then 
		return 
	end

	memberData = Data.members
	OrgName = Data.groupName
	max = Data.max
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- CLOSE
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("removeFocus",function(Data,Callback)
	TransitionFromBlurred(1000)
	SetNuiFocus(false,false)
	Callback({})
	vRP.Destroy()
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- invite
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("inviteMember",function(Data,Callback)
	local res = vSERVER.Invite(Data)
	if res then 
		MemberList()
	end
	Callback({})
	vRP.Destroy()
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- PROMOTE
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("promoteMember",function(Data,Callback)
	local res = vSERVER.Hierarchy(Data,"Promote")
	if res then 
		MemberList()
	end
	Callback({})
	vRP.Destroy()
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- DEMOTE
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("demoteMember",function(Data,Callback)
	local res = vSERVER.Hierarchy(Data,"Demote")
	if res then 
		MemberList()
	end
	Callback({})
	vRP.Destroy()
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- DISMISS
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("dismissMember",function(Data,Callback)
	local res = vSERVER.Dismiss(Data)
	if res then 
		MemberList()
	end
	Callback({})
	vRP.Destroy()
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- DISMISS
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("updateData",function(Data,Callback)
	Callback({ orgName = OrgName, memberList = memberData, max = max, totalOnline = MembersOnline })
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- PAINEL:UPDATE
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNetEvent("painel:Update")
AddEventHandler("painel:Update",function(groupName)
	ExecuteCommand("Painel "..groupName)
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- WITHDRAW
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("withdraw", function(data, cb)
	vSERVER._Withdraw(data.amount)
	TransitionFromBlurred(1000)
	SetNuiFocus(false,false)
	SendNUIMessage({ action = "closeUi" })
	vRP.Destroy()
	cb(true)
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- UPDATEEXTRACTS
-----------------------------------------------------------------------------------------------------------------------------------------

-----------------------------------------------------------------------------------------------------------------------------------------
-- VRP
-----------------------------------------------------------------------------------------------------------------------------------------
local Tunnel = module("vrp", "lib/Tunnel")
local Proxy = module("vrp", "lib/Proxy")
vRP = Proxy.getInterface("vRP")
-----------------------------------------------------------------------------------------------------------------------------------------
-- CONNECTION
-----------------------------------------------------------------------------------------------------------------------------------------
vCLIENT = {}
Tunnel.bindInterface(GetCurrentResourceName(), vCLIENT)
Creative = Tunnel.getInterface(GetCurrentResourceName())
-----------------------------------------------------------------------------------------------------------------------------------------
-- VARIABLES
-----------------------------------------------------------------------------------------------------------------------------------------
local notify = true
local count = false
local countSeconds = 0
-----------------------------------------------------------------------------------------------------------------------------------------
-- UPDATECALLS
-----------------------------------------------------------------------------------------------------------------------------------------
function vCLIENT.updateCalls()
    SendNUIMessage({update = Creative.getCalls()})
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- COUNTTIME
-----------------------------------------------------------------------------------------------------------------------------------------
function vCLIENT.countTime()
    count = true
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- GETTIME
-----------------------------------------------------------------------------------------------------------------------------------------
function vCLIENT.getTime()
    return config["Timeout"] - countSeconds
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- GETNOTIFY
-----------------------------------------------------------------------------------------------------------------------------------------
function vCLIENT.getNotify()
    return Notify
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- THREAD
-----------------------------------------------------------------------------------------------------------------------------------------
CreateThread(function()
    while true do
        local wait = 1

        if count then
            countSeconds = countSeconds + 1
            wait = 1000

            if countSeconds >= config["Timeout"] then
                count = false
                countSeconds = 0
                wait = 1
            end
        end
        
        Wait(wait)
    end
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- REGISTERCOMMAND
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterCommand("+openCall", function()
    if Creative.checkPermission() then
        SetNuiFocus(true, true)
        SendNUIMessage({open = true, update = Creative.getCalls()})
    end
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- NOTIFY
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("notify", function(data, cb)
    notify = not notify
    cb({notify = notify})

    if notify then
        TriggerEvent("Notify","verde","Você ativou as notificações!",5000)
    else
        TriggerEvent("Notify","verde","Você desativou as notificações!",5000)
    end
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- ACCEPT
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("accept", function(data)
    Creative._accept(data.id)
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- CLOSE
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("close", function()
    SetNuiFocus(false, false)
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- KEYMAPPING
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterKeyMapping("+openCall", "", "keyboard", config["Bind"])
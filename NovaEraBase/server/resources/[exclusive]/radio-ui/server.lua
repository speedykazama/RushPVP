local Tunnel = module('vrp', 'lib/Tunnel')
local Proxy = module('vrp', 'lib/Proxy')
local vRP = Proxy.getInterface('vRP')
-----------------------------------------------------------------------------------------------------------------------------------------
-- CONNECTION
-----------------------------------------------------------------------------------------------------------------------------------------
Creative = {}
Tunnel.bindInterface("radio-ui",Creative)
-----------------------------------------------------------------------------------------------------------------------------------------
-- GETPLAYER
-----------------------------------------------------------------------------------------------------------------------------------------
function Creative.GetPlayer(plySource)
    local Passport = vRP.Passport(plySource)
    if Passport then
        local identity = vRP.Identity(Passport)

        return '#' .. Passport .. ' ' .. (identity.name or '') .. ' ' .. (identity.name2 or '')
    end
end